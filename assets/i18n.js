(function () {
  var KEY = "iguana-lang";
  var lang = "en";
  try { lang = localStorage.getItem(KEY) || ""; } catch (e) {}
  if (!lang) lang = (navigator.language || "en").toLowerCase().indexOf("es") === 0 ? "es" : "en";
  var listeners = [];

  window.t = function (key, vars) {
    var s = (window.I18N[lang] && window.I18N[lang][key]) || window.I18N.en[key] || key;
    if (vars) for (var k in vars) s = s.split("{" + k + "}").join(vars[k]);
    return s;
  };
  window.getLang = function () { return lang; };
  window.onLangChange = function (fn) { listeners.push(fn); };

  function apply() {
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach(function (el) { el.innerHTML = window.t(el.getAttribute("data-i18n")); });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) { el.setAttribute("aria-label", window.t(el.getAttribute("data-i18n-aria"))); });
    listeners.forEach(function (fn) { fn(lang); });
  }
  window.applyI18n = apply;

  document.addEventListener("click", function (e) {
    var b = e.target.closest && e.target.closest("[data-lang-toggle]");
    if (!b) return;
    lang = lang === "en" ? "es" : "en";
    try { localStorage.setItem(KEY, lang); } catch (err) {}
    apply();
  });
})();
